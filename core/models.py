from typing import List, Optional, Dict
from pydantic import BaseModel, Field


class AudioClipMetadata(BaseModel):
    """Output schema from Agent 1 (Viral Audio & Hook Extractor)."""
    song_name: str
    movie_or_artist: str
    start_sec: float = Field(..., description="Start timestamp of viral hook in seconds")
    end_sec: float = Field(..., description="End timestamp of viral hook in seconds")
    duration_sec: float = Field(..., description="Duration of viral segment (15-30s)")
    virality_score: int = Field(..., ge=0, le=100, description="Virality confidence rating")
    bpm: int = Field(default=105, description="Beats per minute")
    energy_level: str = Field(default="High Emotional Peak", description="Perceived audio energy")
    sentiment: str = Field(default="Romantic Nostalgia", description="Overall audio emotional vibe")
    key_hook_line: str = Field(..., description="The most memorable catchphrase/hook line")
    lyrics_excerpt: str = Field(..., description="Lyrics corresponding to this viral hook")
    audio_file_path: Optional[str] = Field(None, description="Path to extracted audio clip")


class LyricChunk(BaseModel):
    """Micro-sentence parsed by Agent 2 for synchronised scene pacing."""
    chunk_id: int
    text: str
    start_time: float
    end_time: float
    duration: float
    sentiment_tag: str
    visual_intent: str


class SceneAsset(BaseModel):
    """Visual asset storyboard card generated or harvested by Agent 2."""
    scene_id: int
    chunk: LyricChunk
    image_url: str
    ai_prompt: str
    aesthetic_vibe: str
    color_palette: List[str]
    motion_effect: str = "Ken Burns Slow Zoom In"
    aspect_ratio: str = "9:16"


class StoryboardPlan(BaseModel):
    """Full visual storyboard pack generated by Agent 2."""
    song_name: str
    movie_or_artist: str
    vibe_theme: str
    aesthetic_dna: Dict[str, str]
    scenes: List[SceneAsset]


class InstagramPublishingPack(BaseModel):
    """Final package produced by Agent 3 for one-click publishing."""
    video_output_path: str
    duration_sec: float
    aspect_ratio: str = "9:16 (1080x1920)"
    caption_hook: str
    caption_body: str
    full_caption: str
    hashtags: List[str]
    recommended_post_time: str
    audio_credit: str
    creator: str = "Bhagirath Argade"
